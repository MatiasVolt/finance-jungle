// t('home.days', { n: 3 }) → « 3 jours de suite ». {n|singulier|pluriel} accorde selon n.
export function translate(lang, key, vars = {}) {
  const s = UI[lang][key] ?? UI.fr[key] ?? key
  return s
    .replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_, k, one, many) => `${vars[k]} ${Number(vars[k]) > 1 ? many : one}`)
    .replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`))
}

// Un texte du catalogue : soit une chaîne, soit { fr, en }.
export const pick = (v, lang) => (typeof v === 'string' ? v : v?.[lang] ?? v?.fr)

export const locale = lang => (lang === 'fr' ? 'fr-FR' : 'en-GB')
export const fmt = (v, lang, opts) => v.toLocaleString(locale(lang), opts)

export const LangContext = createContext({ lang: 'fr', setLang: () => {} })

export function useLang() {
  const { lang, setLang } = useContext(LangContext)
  return { lang, setLang, t: (key, vars) => translate(lang, key, vars), p: v => pick(v, lang) }
}
